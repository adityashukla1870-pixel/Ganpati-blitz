export const EMOJI_TO_AVATAR_MAP = {
  '🐘': 'shree-ganesha',
  '🥟': 'sacred-modak',
  '🪔': 'divine-diya',
  '🪷': 'sacred-padma',
  '🥁': 'royal-dhol',
  '🐭': 'mushak-vahana',
  '🎨': 'mandala-rangoli',
  '⚡': 'sudarshan-chakra',
  '🧠': 'omkara-crest',
  '🔥': 'rudra-trishul',
  '👑': 'maharaja-crown',
  '🏆': 'vijay-kalash',
}

export function resolveAvatarId(avatarOrEmoji) {
  if (!avatarOrEmoji) return 'shree-ganesha'
  if (EMOJI_TO_AVATAR_MAP[avatarOrEmoji]) {
    return EMOJI_TO_AVATAR_MAP[avatarOrEmoji]
  }
  const match = AVATAR_LIST.find((a) => a.id === avatarOrEmoji)
  if (match) return match.id
  return 'shree-ganesha'
}

export function getAvatarMeta(avatarOrEmoji) {
  const resolvedId = resolveAvatarId(avatarOrEmoji)
  return AVATAR_LIST.find((a) => a.id === resolvedId) || AVATAR_LIST[0]
}
